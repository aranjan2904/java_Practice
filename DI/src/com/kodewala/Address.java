package com.kodewala;

public class Address {
	private String floor;
	private String apartment;
	private String pin;
	private String state;
	
	public Address(String floor, String apartment, String pin, String state) {
		super();
		this.floor = floor;
		this.apartment = apartment;
		this.pin = pin;
		this.state = state;
	}
	
}
